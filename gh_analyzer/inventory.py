"""Stage 3 of M03: what is actually in the repository, excluding the world.

A repository that is 95% node_modules must not look enormous (Trap 3), so lines
are counted only for recognised source files that are not vendored, generated,
binary or oversized. Every exclusion has a reason that can be listed.
"""

from __future__ import annotations

import fnmatch
import json
import os
import re
from dataclasses import dataclass, field
from pathlib import Path

CODE_EXT = {
    ".py": "Python", ".js": "JavaScript", ".jsx": "JavaScript", ".mjs": "JavaScript", ".ts": "TypeScript",
    ".tsx": "TypeScript", ".java": "Java", ".c": "C", ".h": "C", ".cpp": "C++", ".cc": "C++", ".hpp": "C++",
    ".cs": "C#", ".go": "Go", ".rs": "Rust", ".rb": "Ruby", ".php": "PHP", ".kt": "Kotlin", ".swift": "Swift",
    ".sql": "SQL", ".sh": "Shell", ".html": "HTML", ".css": "CSS", ".scss": "CSS", ".dart": "Dart",
    ".ipynb": "Jupyter",
}
EXCLUDE_DIRS = {
    "node_modules", "venv", ".venv", "dist", "build", "target", "vendor", "__pycache__", ".git", ".next",
    "coverage", "migrations", "site-packages", ".idea", ".vscode", ".pytest_cache", ".mypy_cache", ".tox",
}
EXCLUDE_GLOBS = ["*.min.js", "*.min.css", "*.lock", "*-lock.json", "package-lock.json", "*.pb.go", "*.pb.cc",
                 "*.map", "*_pb2.py", "*_pb2_grpc.py"]
GENERATED_MARKERS = re.compile(r"(code generated|@generated|do not edit|auto-?generated|generated by)", re.I)
MAX_FILE_BYTES = 500 * 1024
TEST_NAME = re.compile(r"(^test_.*\.py$|.*_test\.py$|.*\.(test|spec)\.[jt]sx?$|.*Test\.java$)")
KNOWN_FRAMEWORKS = {
    "flask", "django", "fastapi", "tensorflow", "torch", "pytorch", "scikit-learn", "sklearn", "keras", "pandas",
    "numpy", "react", "vue", "angular", "express", "next", "svelte", "spring-boot", "streamlit", "gradio",
    "transformers", "langchain", "sqlalchemy", "prisma", "mongoose", "tailwindcss", "vite", "opencv-python",
}
CI_PATHS = (".github/workflows", ".gitlab-ci.yml", ".travis.yml", "Jenkinsfile", ".circleci")


def path_excluded(rel: str) -> str | None:
    """Reason a path is excluded from analysis by name alone, or None. Usable on paths from `git log`."""
    parts = rel.split("/")
    for part in parts[:-1]:
        if part in EXCLUDE_DIRS:
            return f"inside {part}/"
    name = parts[-1]
    for g in EXCLUDE_GLOBS:
        if fnmatch.fnmatch(name, g):
            return f"matches {g}"
    return None


def is_code(rel: str) -> bool:
    return Path(rel).suffix.lower() in CODE_EXT


def is_test_path(rel: str) -> bool:
    parts = rel.split("/")
    return any(p in ("tests", "test", "__tests__") for p in parts[:-1]) or bool(TEST_NAME.match(parts[-1]))


def notebook_lines(path: Path) -> int:
    try:
        nb = json.loads(path.read_text(encoding="utf-8", errors="replace"))
        return sum(1 for c in nb.get("cells", []) if c.get("cell_type") == "code"
                   for ln in c.get("source", []) if str(ln).strip())
    except (json.JSONDecodeError, OSError, AttributeError):
        return 0


def _looks_binary(head: bytes) -> bool:
    return b"\x00" in head


@dataclass
class Inventory:
    total_files: int = 0
    analysed_files: int = 0
    excluded_files: int = 0
    loc_total: int = 0
    loc_excluded: int = 0
    languages: dict[str, int] = field(default_factory=dict)
    frameworks: list[str] = field(default_factory=list)
    dependencies: list[str] = field(default_factory=list)
    has_tests: bool = False
    test_loc: int = 0
    has_ci: bool = False
    has_dockerfile: bool = False
    has_readme: bool = False
    readme_quality: float = 0.0
    licence: str | None = None
    scaffold_ratio: float | None = None          # not implemented: needs a scaffold fingerprint list
    analysed: list[str] = field(default_factory=list)
    exclusion_reasons: dict[str, int] = field(default_factory=dict)

    def to_dict(self) -> dict:
        d = dict(self.__dict__)
        d.pop("analysed")
        return d


def _count_lines(path: Path) -> int:
    n = 0
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for ln in fh:
            if ln.strip():
                n += 1
    return n


def _deps_from(root: Path) -> list[str]:
    deps: list[str] = []
    req = root / "requirements.txt"
    if req.is_file():
        for ln in req.read_text(encoding="utf-8", errors="replace").splitlines():
            ln = ln.split("#")[0].strip()
            if ln and not ln.startswith("-"):
                m = re.match(r"[A-Za-z0-9_.\-]+", ln)
                if m:
                    deps.append(m.group(0).lower())
    pj = root / "package.json"
    if pj.is_file():
        try:
            data = json.loads(pj.read_text(encoding="utf-8", errors="replace"))
            for key in ("dependencies", "devDependencies"):
                deps += [k.lower() for k in (data.get(key) or {})]
        except (json.JSONDecodeError, AttributeError):
            pass
    pp = root / "pyproject.toml"
    if pp.is_file():
        text = pp.read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(r'"([A-Za-z0-9_.\-]+)\s*(?:[<>=!~\[;].*?)?"', text):
            deps.append(m.group(1).lower())
    return sorted(set(deps))


def readme_quality(text: str) -> float:
    """0 to 1. CONVENTION, not measured: length, a code block, and a setup or usage heading, equally simple parts."""
    words = len(text.split())
    score = 0.5 * min(1.0, words / 150)
    score += 0.25 if "```" in text or "\n    " in text else 0.0
    score += 0.25 if re.search(r"^#+\s*.*(install|usage|run|setup|getting started)", text, re.I | re.M) else 0.0
    return round(score, 2)


def scan(root: Path) -> Inventory:
    inv = Inventory()
    root = Path(root)
    reasons: dict[str, int] = {}

    def exclude(why: str) -> None:
        inv.excluded_files += 1
        reasons[why] = reasons.get(why, 0) + 1

    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        rel_dir = Path(dirpath).relative_to(root).as_posix()
        if rel_dir == ".git" or rel_dir.startswith(".git/"):
            dirnames[:] = []
            continue
        skipped = [d for d in dirnames if d in EXCLUDE_DIRS]
        for d in skipped:                      # not descended into: recorded as one exclusion each
            exclude(f"directory {d}/ skipped")
        dirnames[:] = [d for d in dirnames if d not in EXCLUDE_DIRS]
        for fn in filenames:
            full = Path(dirpath) / fn
            if full.is_symlink():
                continue
            rel = (Path(rel_dir) / fn).as_posix() if rel_dir != "." else fn
            inv.total_files += 1
            low = fn.lower()
            if low.startswith("readme") and rel_dir == ".":
                inv.has_readme = True
                try:
                    inv.readme_quality = readme_quality(full.read_text(encoding="utf-8", errors="replace"))
                except OSError:
                    pass
            if low in ("licence", "license", "licence.md", "license.md", "licence.txt", "license.txt", "copying"):
                inv.licence = _licence_kind(full)
            if low == "dockerfile" or low.endswith(".dockerfile") or low == "docker-compose.yml":
                inv.has_dockerfile = True
            if any(rel == c or rel.startswith(c + "/") for c in CI_PATHS):
                inv.has_ci = True
            if not is_code(rel):
                continue
            why = path_excluded(rel)
            if why:
                exclude(why)
                try:
                    inv.loc_excluded += _count_lines(full) if full.suffix != ".ipynb" else 0
                except OSError:
                    pass
                continue
            try:
                size = full.stat().st_size
                with open(full, "rb") as fh:
                    head = fh.read(8192)
            except OSError:
                exclude("unreadable")
                continue
            if size > MAX_FILE_BYTES:
                exclude("larger than 500 KB")
                continue
            if _looks_binary(head):
                exclude("binary")
                continue
            if GENERATED_MARKERS.search("\n".join(head.decode("utf-8", errors="replace").splitlines()[:5])):
                exclude("generated header")
                continue
            lang = CODE_EXT[full.suffix.lower()]
            loc = notebook_lines(full) if full.suffix.lower() == ".ipynb" else _count_lines(full)
            inv.analysed_files += 1
            inv.analysed.append(rel)
            inv.loc_total += loc
            inv.languages[lang] = inv.languages.get(lang, 0) + loc
            if is_test_path(rel):
                inv.has_tests = True
                inv.test_loc += loc
    deps = _deps_from(root)
    inv.dependencies = deps
    inv.frameworks = sorted({d for d in deps if d in KNOWN_FRAMEWORKS})
    inv.languages = dict(sorted(inv.languages.items(), key=lambda kv: -kv[1]))
    inv.exclusion_reasons = dict(sorted(reasons.items(), key=lambda kv: -kv[1]))
    return inv


def _licence_kind(path: Path) -> str:
    try:
        head = path.read_text(encoding="utf-8", errors="replace")[:600].lower()
    except OSError:
        return "present"
    for key, name in (("mit license", "MIT"), ("apache license", "Apache-2.0"), ("gnu general public", "GPL"),
                      ("bsd", "BSD"), ("mozilla public", "MPL-2.0"), ("unlicense", "Unlicense")):
        if key in head:
            return name
    return "present"
